param([string]$CopperFSRoot = (Join-Path $PSScriptRoot '../../CopperFS'))

$ErrorActionPreference = 'Stop'
$repoRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$sourceRoot = [IO.Path]::GetFullPath($CopperFSRoot)
$destinationRoot = [IO.Path]::GetFullPath((Join-Path $repoRoot 'CopperScreen.FileSystems/Upstream/CopperFS'))
$sourceFiles = @('LICENSE', 'prototypes/CopperFS.Prototype/WideMath32.cs')
foreach ($folder in @('CopperFFS.Core', 'CopperSFS.Core', 'CopperCPX.Core')) {
    $directory = Join-Path $sourceRoot "src/$folder"
    if (!(Test-Path -LiteralPath $directory -PathType Container)) { throw "Missing CopperFS source directory: $directory" }
    $files = @(Get-ChildItem -LiteralPath $directory -Filter '*.cs' -File | Sort-Object Name)
    if (!$files.Count) { throw "No maintained sources found in $directory" }
    $sourceFiles += $files | ForEach-Object { "src/$folder/$($_.Name)" }
}

# Freeze bytes first. Reject a changing source set before replacing any snapshot files.
$inputs = foreach ($relative in $sourceFiles) {
    $bytes = [IO.File]::ReadAllBytes((Join-Path $sourceRoot $relative))
    [pscustomobject]@{ path = $relative; bytes = $bytes; sha256 = [Convert]::ToHexString([Security.Cryptography.SHA256]::HashData($bytes)) }
}
foreach ($inputFile in $inputs) {
    if ((Get-FileHash -LiteralPath (Join-Path $sourceRoot $inputFile.path) -Algorithm SHA256).Hash -cne $inputFile.sha256) {
        throw "CopperFS changed while being read: $($inputFile.path). Rerun after the change finishes."
    }
}
$head = & git -C $sourceRoot rev-parse HEAD
if ($LASTEXITCODE) { throw 'Cannot identify the CopperFS source repository.' }
$status = @(& git -C $sourceRoot status --porcelain --untracked-files=all -- src/CopperFFS.Core src/CopperSFS.Core src/CopperCPX.Core prototypes/CopperFS.Prototype/WideMath32.cs LICENSE)
if ($LASTEXITCODE) { throw 'Cannot record CopperFS working-tree provenance.' }
$manifestPath = Join-Path $destinationRoot 'snapshot.json'
if (Test-Path -LiteralPath $manifestPath) {
    $old = Get-Content -LiteralPath $manifestPath -Raw | ConvertFrom-Json
    foreach ($file in $old.files) {
        if ($file.path -notin $sourceFiles -and (Test-Path -LiteralPath (Join-Path $destinationRoot $file.path))) {
            throw "Upstream removed $($file.path). Review and remove the obsolete snapshot file before importing a new source set."
        }
    }
}
foreach ($inputFile in $inputs) {
    $target = [IO.Path]::GetFullPath((Join-Path $destinationRoot $inputFile.path))
    if (!$target.StartsWith($destinationRoot + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)) { throw 'Invalid snapshot target.' }
    [IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($target)) | Out-Null
    [IO.File]::WriteAllBytes($target, $inputFile.bytes)
}
$manifest = [ordered]@{
    schemaVersion = 1
    repository = 'https://github.com/ilehtoranta/CopperFS.git'
    baseCommit = $head.Trim()
    sourceKind = 'working-tree snapshot; file hashes identify the exact inputs, including uncommitted CPX development'
    sourceStatus = $status
    files = @($inputs | ForEach-Object { [ordered]@{ path = $_.path; sha256 = $_.sha256 } })
}
[IO.File]::WriteAllText($manifestPath, ($manifest | ConvertTo-Json -Depth 5) + "`n")
$items = foreach ($inputFile in $inputs) {
    '    <_CopperFsSnapshotInput Include="$(MSBuildThisFileDirectory)' + $inputFile.path + '" ExpectedHash="' + $inputFile.sha256 + '" />'
}
$props = "<Project>`n  <!-- Generated by scripts/update-copperfs-snapshot.ps1. -->`n  <ItemGroup>`n" + ($items -join "`n") + "`n  </ItemGroup>`n</Project>`n"
[IO.File]::WriteAllText((Join-Path $destinationRoot 'snapshot.props'), $props)
Write-Output "Imported $($inputs.Count) CopperFS source/license files. Exact bytes and working-tree provenance are recorded in $manifestPath."
