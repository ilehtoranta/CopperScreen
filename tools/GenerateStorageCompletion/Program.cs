using System.Buffers.Binary;
using System.Security.Cryptography;
using System.Text;
using CopperSharp.Compiler;
using CopperSharp.Targets.Amiga;
using CopperScreen.Storage;

if (args.Length != 1) throw new ArgumentException("Supply generated C# output path.");
var result = AmigaM68kCompiler.Compile(new()
{
    AssemblyPath = typeof(Completion).Assembly.Location,
    EntryPoint = "CopperScreen.Storage.Completion::Root", IncludedExportNames = [],
    Cpu = M68kCpuTarget.M68000, OutputFormat = M68kOutputFormat.Hunk,
    RuntimeProfile = M68kRuntimeProfile.Freestanding, MemoryManagement = M68kMemoryManagement.None,
    ExceptionMode = M68kExceptionMode.Yolo, PeepholeOptimization = M68kPeepholeOptimizationMode.FixedPoint,
    CodeSizeOptimizations = new() { InlineMemoryHelpers = true, CompactGuestMemory = true, RemoveRedundantTransport = true }
});
if (!result.FrameworkAnalysis.IsCompatible || result.FrameworkAnalysis.ManagedAllocationSites.Count != 0)
    throw new InvalidOperationException("Completion routines must be native and allocation-free.");
uint Address(string name) => result.Symbols.Single(s => s.Name == "CopperScreen.Storage.Completion::" + name).Address;
var relocations = result.Relocations.Select(r => r.Offset).Distinct().Order().ToArray();
foreach (var offset in relocations)
    if (offset < 0 || offset > result.Code.Length - 4 || BinaryPrimitives.ReadUInt32BigEndian(result.Code.AsSpan(offset, 4)) >= result.Code.Length)
        throw new InvalidOperationException("Completion code has a relocation outside its owned image.");
var text = new StringBuilder("// Generated by tools/GenerateStorageCompletion from C#; do not edit instruction bytes.\n");
text.AppendLine($"// Linked code SHA-256: {Convert.ToHexString(SHA256.HashData(result.Code))}");
text.AppendLine("namespace CopperMod.Amiga.Lightweight;\ninternal static class LightweightStorageCompletionCode\n{");
text.AppendLine($"    internal const uint InitializeOffset = {Address("Initialize")};");
text.AppendLine($"    internal const uint InterruptOffset = {Address("Interrupt")};");
text.AppendLine("    internal static readonly byte[] Image =\n    [");
for (var at = 0; at < result.Code.Length; at += 16)
    text.AppendLine("        " + string.Join(", ", result.Code.Skip(at).Take(16).Select(b => $"0x{b:X2}")) + ",");
text.AppendLine("    ];");
text.AppendLine("    internal static readonly int[] Relocations = [" + string.Join(", ", relocations) + "];\n}");
File.WriteAllText(args[0], text.ToString());
Console.WriteLine($"Generated {result.Code.Length} native bytes, {relocations.Length} relocations; no managed allocation sites.");
